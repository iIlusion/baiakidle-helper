export function huntById(id: string | null | undefined): HuntEntry | undefined {
  if (!id) return;
  return HUNTS.find(hunt => hunt.id === id);
}

export function huntByName(name: string): HuntEntry | undefined {
  const needle = name.trim().toLowerCase();
  if (!needle) return;
  return HUNTS.find(hunt => hunt.name.toLowerCase() === needle);
}
